// ~/Projects/README.md is the map of the projects folder: a hand-written guide on top, and a list
// of every project underneath that Mission Control rebuilds from the PROJECT.md files (between the
// markers), so the list never drifts. Rebuilt by `mc push`, `mc map` and every SessionEnd hook.
import { existsSync, readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import type { Project } from './format.ts';

export const START = '<!-- PROJECTS:START. Generated by Mission Control (mc map) from each PROJECT.md: edit those, not this list. -->';
export const END = '<!-- PROJECTS:END -->';
const ORDER = ['active', 'paused', 'done', 'archived'] as const;
const LABEL: Record<string, string> = { active: 'Active', paused: 'Paused', done: 'Done', archived: 'Archived' };
const HUB_ID = 'mission-control';

/** The first sentence of the "What it is" section, kept to one table cell. */
export function oneLiner(body: string): string {
  const m = /##\s*What it is\s*\n([\s\S]*?)(?:\n\s*\n|\n##|$)/.exec(body);
  const para = (m ? m[1] : body.replace(/^#.*$/gm, '')).replace(/\s+/g, ' ').trim();
  const s = /^(.+?[.!?])(?=\s|$)/.exec(para)?.[1] ?? para;
  return s.length > 200 ? s.slice(0, 197).trimEnd() + '…' : s;
}

const cell = (s: string) => s.replace(/\|/g, '\\|');

/** The generated section: projects grouped by status, then top-level folders that aren't projects. */
export function renderProjects(projects: Project[], root: string): string {
  const folderOf = (p: Project) => {
    const rel = relative(root, dirname(p.path));
    return rel && !rel.startsWith('..') ? `\`${rel}/\`` : '(no folder)';
  };
  const out: string[] = [];
  for (const status of ORDER) {
    const group = projects
      .filter((p) => p.status === status)
      .sort((a, b) => (a.id === HUB_ID ? -1 : b.id === HUB_ID ? 1 : a.name.localeCompare(b.name)));
    if (!group.length) continue;
    out.push(`### ${LABEL[status]} (${group.length})`, '', '| Project | Folder | For | What it is |', '|---|---|---|---|');
    for (const p of group) {
      const forWho = [p.client ?? 'personal', ...p.tags].join(' · ');
      out.push(`| **${cell(p.name)}** | ${folderOf(p)} | ${cell(forWho)} | ${cell(oneLiner(p.body))} |`);
    }
    out.push('');
  }
  // Top-level folders with no project inside them: loose material, archives, strays.
  const projectTops = new Set(projects.map((p) => relative(root, p.path).split('/')[0]));
  let others: string[] = [];
  try {
    others = readdirSync(root).filter((n) => !n.startsWith('.') && !projectTops.has(n) && statSync(join(root, n)).isDirectory()).sort();
  } catch { /* root missing: no extras */ }
  if (others.length) out.push(`**Not projects:** ${others.map((n) => `\`${n}/\``).join(', ')}`, '');
  return out.join('\n').trimEnd();
}

const FALLBACK_HEAD = `# Projects

One folder per project. Mission Control (\`mission-control/\`) is the hub above all of them.

## Projects
`;

/** Write the generated list into root/README.md, keeping everything outside the markers.
 *  Returns true if the file changed. */
export function writeMap(root: string, projects: Project[]): boolean {
  const file = join(root, 'README.md');
  const section = `${START}\n${renderProjects(projects, root)}\n${END}`;
  const old = existsSync(file) ? readFileSync(file, 'utf8') : null;
  let next: string;
  if (old === null) next = `${FALLBACK_HEAD}\n${section}\n`;
  else {
    const a = old.indexOf('<!-- PROJECTS:START'), b = old.indexOf(END);
    next = a >= 0 && b > a ? old.slice(0, a) + section + old.slice(b + END.length) : `${old.trimEnd()}\n\n${section}\n`;
  }
  if (next === old) return false;
  writeFileSync(file, next);
  return true;
}
